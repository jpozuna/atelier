  it("imports nothing at runtime (type-only imports are fine)", () => {
    const src = readFileSync(fileURLToPath(new URL("./config.ts", import.meta.url)), "utf8");
    const imports = src.match(/^\s*import\b.*$/gm) ?? [];
    for (const line of imports) expect(line).toMatch(/^\s*import type\b/);
    expect(src).not.toMatch(/\brequire\(|\bimport\(/);
  });
